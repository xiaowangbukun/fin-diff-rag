def ensure_seed() -> None:
    db = SessionLocal()
    try:
        if db.execute(select(User)).scalars().first() is not None:
            return
        dept_map: dict[str, str] = {}
        for name, parent in DEPTS:
            d = Department(name=name, parent_id=dept_map.get(parent) if parent else None)
            db.add(d)
            db.flush()
            dept_map[name] = d.id

        user_map: dict[str, str] = {}
        for username, realname, dept, roles, clearance, pwd in USERS:
            h, s = hash_password(pwd)
            u = User(
                username=username, display_name=realname, dept_id=dept_map[dept],
                roles=json.dumps(roles, ensure_ascii=False), clearance=clearance,
                pwd_hash=h, salt=s, status=True,
            )
            db.add(u)
            db.flush()
            user_map[username] = u.id
        db.commit()

        for spec in DOCS:
            doc = ingest_document(
                db, title=spec["title"], content=spec["content"], doc_type="md",
                source_name="系统内置示例", owner_dept_id=dept_map[spec["dept"]],
                clearance=spec["clearance"], acl_mode=spec["acl_mode"],
                tags=spec["tags"], created_by="system",
            )
            # 白名单模式必须给出显式授权，否则任何人都不可见
            if spec["acl_mode"] == "restrict":
                if spec["clearance"] < 3:
                    # 机密级：按角色开放给风控与合规
                    for r in ("risk", "compliance"):
                        db.add(DocAcl(doc_id=doc.id, subject_type="role", subject_key=r,
                                      effect="allow", granted_by="system"))
                # 绝密级不按角色开放；管理员走点对点授权，且全部留痕
                db.add(DocAcl(doc_id=doc.id, subject_type="user",
                              subject_key=user_map["admin"], effect="allow",
                              granted_by="system"))
        db.commit()
    finally:
        db.close()
