def default_password_users(db) -> list[str]:
    """检出仍在用**出厂口令**的账号（金融内网"开箱即用"的最大单点风险）。

    ensure_seed() 为保证演示可跑，给 admin / 业务角色注入固定口令（见 USERS），
    且 seed 幂等重复执行。生产部署若漏改口令，任何人都能用 admin（密级 3，
    可见绝密）登录看全库——这里把它变成启动期的可观测信号：默认告警，
    `ENFORCE_PASSWORD_CHANGE=true` 时拒绝启动（见 config 与 main.lifespan）。

    判定：拿出厂口令逐个 verify_password，命中即"未改密"。只读，不写库。
    """
    stale = []
    for username, _name, _dept, _roles, _clearance, pwd in USERS:
        u = db.execute(
            select(User).where(User.username == username)
        ).scalar_one_or_none()
        if u and verify_password(pwd, u.pwd_hash, u.salt):
            stale.append(username)
    return stale


